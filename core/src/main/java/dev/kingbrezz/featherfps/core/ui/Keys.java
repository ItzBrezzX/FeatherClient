package dev.kingbrezz.featherfps.core.ui;

/** GLFW key codes (the values Minecraft reports) used by the settings screen. */
public final class Keys {
    public static final int TAB = 258, ESCAPE = 256, ENTER = 257, RIGHT = 262, LEFT = 263, DOWN = 264, UP = 265,
            PAGE_UP = 266, PAGE_DOWN = 267, RIGHT_SHIFT = 344, BACKSPACE = 259, F = 70;
    /** GLFW modifier bits: Control, and Super (Command on macOS). */
    public static final int MOD_CONTROL = 2, MOD_SUPER = 8;

    private Keys() {}
}
